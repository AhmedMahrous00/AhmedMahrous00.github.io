import assert from "node:assert/strict";
import worker,{markdownPath,prefersMarkdown} from "./markdown-worker.mjs";
assert.equal(markdownPath("/"),"/index.md");
assert.equal(markdownPath("/cv.html"),"/cv.md");
assert.equal(markdownPath("/papers/pumpsense/"),"/papers/pumpsense/index.md");
assert.equal(markdownPath("/papers/pumpsense/index.html"),"/papers/pumpsense/index.md");
for(const path of ["/papers/pumpsense/paper.pdf","/.well-known/search","/robots.txt","/index.md"])assert.equal(markdownPath(path),null);
for(const h of ["text/markdown","text/markdown,text/html;q=0.9"])assert.equal(prefersMarkdown(h),true);
for(const h of ["text/html","*/*","text/markdown;q=0,text/html","text/markdown;q=0.3,text/html;q=1"])assert.equal(prefersMarkdown(h),false);
const calls=[];
globalThis.fetch=async request=>{
  const path=new URL(request.url).pathname;
  calls.push(path);
  if(path==="/index.md")return new Response(request.method==="HEAD"?null:"# Academic homepage",{headers:{"Content-Type":"text/plain","Vary":"Accept-Encoding"}});
  return new Response(request.method==="HEAD"?null:"<html>original</html>",{headers:{"Content-Type":"text/html"}});
};
let r=await worker.fetch(new Request("https://amahrous.com/",{headers:{Accept:"text/markdown"}}));
assert.equal(await r.text(),"# Academic homepage");
assert.equal(r.headers.get("Content-Type"),"text/markdown; charset=utf-8");
assert.match(r.headers.get("Vary"),/Accept-Encoding, Accept/);
assert.equal(r.headers.get("Cache-Control"),"private, no-store");
r=await worker.fetch(new Request("https://amahrous.com/",{headers:{Accept:"text/html"}}));
assert.equal(await r.text(),"<html>original</html>");
assert.equal(r.headers.get("Vary"),"Accept");
r=await worker.fetch(new Request("https://amahrous.com/",{method:"HEAD",headers:{Accept:"text/markdown"}}));
assert.equal(await r.text(),"");
assert.equal(r.headers.get("Content-Type"),"text/markdown; charset=utf-8");
await worker.fetch(new Request("https://amahrous.com/.well-known/search?q=test",{headers:{Accept:"text/markdown"}}));
assert.equal(calls.at(-1),"/.well-known/search");
r=await worker.fetch(new Request("https://amahrous.com/papers/unknown/",{headers:{Accept:"text/markdown"}}));
assert.equal(r.headers.get("Content-Type"),"text/html");
console.log("PASS: Worker content negotiation and fallback");
